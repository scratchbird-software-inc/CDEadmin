def _format_utc_and_local(utc_iso_str):
    """Format a UTC ISO-8601 timestamp into local + UTC display string."""
    if not utc_iso_str:
        return ''
    try:
        normalized = str(utc_iso_str).strip()
        if normalized.endswith('Z'):
            normalized = normalized[:-1] + '+00:00'
        dt_utc = datetime.datetime.fromisoformat(normalized).astimezone(
            datetime.timezone.utc
        )
        dt_local = dt_utc.astimezone()
        utc_fmt = dt_utc.strftime('%Y-%m-%dT%H:%M:%SZ')
        local_fmt = dt_local.strftime('%Y-%m-%d %H:%M:%S %Z').strip()
        return f'{local_fmt} ({utc_fmt})'
    except Exception:
        return str(utc_iso_str)


def _resolve_build_metadata():
    """Resolve release version, build date/time, and commit across Desktop & Web."""
    web_root = Path(getattr(config, 'ROOT_PATH', Path(__file__).resolve().parents[2]))
    desktop_build_info = web_root.parent / 'BUILD_INFO.json'
    web_build_info = web_root / 'build_info.json'
    commit_hash_file = web_root / 'commit_hash'
    bundle_file = web_root / 'pgadmin' / 'static' / 'js' / 'generated' / 'app.bundle.js'

    release = getattr(config, 'CDEADMIN_VERSION', '0.325-alpha')
    commit_hash = getattr(config, 'COMMIT_HASH', None)
    built_at_utc = ''

    # 1. Read web/build_info.json (generated by yarn git:hash / write_build_info.mjs)
    if web_build_info.is_file():
        try:
            payload = json.loads(web_build_info.read_text(encoding='utf-8'))
            if payload.get('release'):
                release = str(payload['release'])
            if payload.get('commit_hash'):
                commit_hash = str(payload['commit_hash'])
            if payload.get('built_at_utc'):
                built_at_utc = str(payload['built_at_utc'])
        except Exception:
            pass

    # 2. Overlay standalone Desktop package BUILD_INFO.json if present & newer/authoritative
    if desktop_build_info.is_file():
        try:
            pkg_payload = json.loads(desktop_build_info.read_text(encoding='utf-8'))
            if pkg_payload.get('source_revision'):
                commit_hash = str(pkg_payload['source_revision'])
            if pkg_payload.get('built_at_utc'):
                built_at_utc = str(pkg_payload['built_at_utc'])
        except Exception:
            pass

    # 3. Fallback commit_hash from web/commit_hash if updated after server boot
    if not commit_hash and commit_hash_file.is_file():
        try:
            commit_hash = commit_hash_file.read_text(encoding='utf-8').strip()
        except Exception:
            pass

    # 4. Fallback build timestamp from compiled production bundle mtime
    if not built_at_utc and bundle_file.is_file():
        try:
            mtime = os.path.getmtime(bundle_file)
            dt_utc = datetime.datetime.fromtimestamp(mtime, tz=datetime.timezone.utc)
            built_at_utc = dt_utc.strftime('%Y-%m-%dT%H:%M:%SZ')
        except Exception:
            pass

    build_datetime = _format_utc_and_local(built_at_utc) if built_at_utc else ''
    return {
        'release': release,
        'commit_hash': commit_hash,
        'build_timestamp_utc': built_at_utc or None,
        'build_datetime': build_datetime or None,
    }


class AboutModule(PgAdminModule):
    def get_own_menuitems(self):
        appname = config.APP_NAME

        return {
            'help_items': [
                MenuItem(
                    name='mnu_about',
                    priority=999,
                    module="pgAdmin.About",
                    callback='about_show',
                    icon='fa fa-info-circle',
                    label=gettext('About %(appname)s', appname=appname)
                )
            ]
        }

    def get_exposed_url_endpoints(self):
        return ['about.index']


blueprint = AboutModule(MODULE_NAME, __name__, static_url_path='')


