"""Convert monitoring dashboards to and from the one BI dashboard document.

Monitoring dashboards are ``ddn-source-workspace@1`` snapshots holding a single
``dashboard.ddn`` (see ``static/js/cdeadmin_ui/integrations/ddn/
dashboardPanels.js``): a keyed host ``source`` named ``metric_feed``, one
``data`` table ``observations`` (``id, panel, measure, value, unit, rate``), a
``table.records@1`` view per panel and ``panels.composed@1`` page views.

The BI document (``dashboard_models.py``) represents that as:

=============================  ==========================================
DDN                            BI dashboard document
=============================  ==========================================
``source metric_feed`` channel ``settings.monitoring.channel`` / ``module``
composed page view             one tab (``id`` = view id, ``name`` = title)
composed ``columns``           ``settings.monitoring.columns``
composed panel entry           one ``metric_panel`` card (title = entry
                               title, ``panel_id`` = observations panel)
entry ``layout`` row/column    ``layout`` on the 24-column grid
                               (``w = 24 / columns``, ``h = 8``)
``observations`` rows          ``metric_panel.rows`` of that panel
=============================  ==========================================

This is a converter, not a second dashboard editor: viewer, collector and the
DDN dashboard editor keep their own paths (``dashboard_definitions.py``).
Whatever the BI document can express but DDN cannot (question cards, text,
filters, links, custom layout) is dropped on export and listed in ``loss``;
whatever DDN holds that the document cannot is listed on import.  The writer
below reproduces ``dashboardPanelFiles`` byte for byte, which a test checks
against fixtures generated by the JavaScript encoder.

Known limit: label truncation counts Python characters, the JavaScript
encoder counts UTF-16 units; they differ only for astral characters in
labels longer than 1024.
"""

from __future__ import annotations

import json
import re

from .dashboard_models import validate_dashboard
from .models import BIError

DDN_CONTRACT = 'ddn-next-1'
DDN_FORMAT = 'ddn-source-workspace@1'
METRIC_COLUMNS = ('id', 'panel', 'measure', 'value', 'unit', 'rate')
VIEW_COLUMNS = (('measure', 'Measure'), ('value', 'Value'),
                ('unit', 'Unit / meaning'), ('rate', 'Per second'))
PAGE_PANELS = 12
CARD_HEIGHT = 8
_CHANNEL_SUFFIX = '.observations'
_CARD_ID = re.compile(r'^[A-Za-z][A-Za-z0-9_-]{0,127}$')


class ConversionError(BIError):
    """The document cannot be converted at all (not merely with loss)."""


def _loss(code, severity, detail):
    return {'code': code, 'severity': severity, 'detail': detail}


# ---------------------------------------------------------------------------
# Writer: a port of source.js / dashboardPanels.js
# ---------------------------------------------------------------------------
def quote_text(value):
    text = str(value)
    if re.search(r'[\r\n\x00]', text):
        raise ConversionError(
            'DDN structural names cannot contain line breaks or NUL')
    return '"' + text.replace('"', '""') + '"'


def display_text(value):
    if isinstance(value, str) and re.search(r'[\r\n\x00]', value):
        return json.dumps(value, ensure_ascii=False)[1:-1]
    return value


def label_text(value):
    text = str(display_text(value))
    return text if len(text) <= 1024 else text[:1023] + '…'


def _scalar(value):
    if isinstance(value, str):
        return quote_text(value)
    if value is None or isinstance(value, bool):
        return json.dumps(value)
    if isinstance(value, (int, float)):
        return json.dumps(value)
    raise ConversionError('unsupported DDN scalar')


def _value_source(key, value, indent):
    lead = ' ' * indent + key
    if isinstance(value, list):
        if not value:
            return lead + ' empty list\n'
        return lead + '\n' + ''.join(
            _value_source('item', row, indent + 4) for row in value)
    if isinstance(value, dict):
        if not value:
            return lead + ' empty record\n'
        return lead + '\n' + _properties(value, indent + 4)
    if isinstance(value, str) and re.search(r'[\r\n]', value):
        return lead + '\n' + '\n'.join(
            ' ' * (indent + 4) + line for line in value.split('\n')) + '\n'
    return lead + ' ' + _scalar(value) + '\n'


def _properties(record, indent=8):
    return ''.join(_value_source(
        quote_text(key) if key == 'item' or re.search(r'[\s"\']', key)
        else key, value, indent) for key, value in record.items())


def _declaration(kind, ident, role, record):
    return (f'{kind} {quote_text(ident)}'
            f'{" as " + quote_text(role) if role else ""}\n    with\n'
            f'{_properties({"id": ident, **record})}\n')


def _ref(ident):
    return {'id': ident}


def _view_source(ident, title, profile, options, records=()):
    extra = {'description': str(title)} if len(str(title)) > 1024 else {}
    merged = dict(options)
    if records:
        merged['records'] = [_ref(row) if isinstance(row, str) else row
                             for row in records]
    return _declaration('view', ident, profile, {
        'title': label_text(title), **extra,
        'selection': {'include': []},
        'projection': {'options': merged}})


def dashboard_panel_files(panels, title, module):
    """Python port of ``dashboardPanelFiles`` (byte-identical output)."""
    seen, rows = set(), []
    for panel in panels:
        for index, row in enumerate(panel['rows']):
            ident = row.get('id') or f"{panel['id']}_{index}"
            if not re.fullmatch(r'[a-z][a-z0-9_]{0,2047}', ident) or (
                    ident in seen):
                raise ConversionError('invalid dashboard binding identity')
            seen.add(ident)
            rows.append([ident, panel['id']] + [
                display_text(str(row.get(name, default)))
                for name, default in (('measure', 'Unavailable'),
                                      ('value', 'Unavailable'),
                                      ('unit', ''), ('rate', ''))])
    feed = _declaration('source', 'metric_feed', 'host', {
        'channel': module + _CHANNEL_SUFFIX, 'update': 'keyed'})
    data = _declaration('data', 'observations', None, {
        'columns': [{'id': name, 'type': 'text'} for name in METRIC_COLUMNS],
        'rows': rows, 'source': _ref('metric_feed'), 'key': 'id'})
    view_ids, used = {}, set()
    for index, panel in enumerate(panels):
        ident = panel['id'] if len(panel['id']) <= 256 else (
            f'panel_long_{index}')
        while ident in used:
            ident += 'x'
        used.add(ident)
        view_ids[panel['id']] = ident
    columns = [{'id': name, 'label': label} for name, label in VIEW_COLUMNS]
    # as in JS: views are joined with a newline
    views = '\n'.join(_view_source(
        view_ids[p['id']], p['title'], 'table.records@1',
        {'columns': columns,
         'filter': [{'key': 'panel', 'op': 'eq', 'value': p['id']}]},
        ['observations']) for p in panels)
    pages = []
    for offset in range(0, len(panels), PAGE_PANELS):
        page = panels[offset:offset + PAGE_PANELS]
        number = len(pages) + 1
        pages.append(_view_source(
            'dashboard' if number == 1 else f'dashboard_page_{number}',
            title if number == 1 else f'{title} — page {number}',
            'panels.composed@1', {
                'columns': 2,
                'panels': [{
                    'target': _ref(view_ids[panel['id']]), 'kind': 'view',
                    'title': label_text(panel['title']),
                    'layout': {'row': index // 2, 'column': index % 2}}
                    for index, panel in enumerate(page)]}))
    header = f'version {DDN_CONTRACT}\n// ScratchRobin mapping: {module}\n\n'
    return {'dashboard.ddn': header + feed + data + views + '\n'.join(pages)}


# ---------------------------------------------------------------------------
# Reader for the writer's own dialect (not a general DDN parser)
# ---------------------------------------------------------------------------
_DECL = re.compile(
    r'^(\w+) ("(?:[^"]|"")*")(?: as ("(?:[^"]|"")*"))?$')
_KEY = re.compile(r'^("(?:[^"]|"")*"|\S+)(?: (.*))?$')


def _unquote(token):
    return token[1:-1].replace('""', '"')


def _scalar_value(text):
    if text.startswith('"'):
        if not re.fullmatch(r'"(?:[^"]|"")*"', text):
            raise ConversionError('malformed DDN string')
        return _unquote(text)
    try:
        return json.loads(text)
    except ValueError:
        raise ConversionError(f'unsupported DDN value {text!r}') from None


def _indent(line):
    return len(line) - len(line.lstrip(' '))


def _nodes(lines, indent):
    nodes, index = [], 0
    while index < len(lines):
        line = lines[index]
        if _indent(line) != indent:
            raise ConversionError('inconsistent DDN indentation')
        match = _KEY.match(line.strip())
        if match is None:
            raise ConversionError('malformed DDN property')
        key, rest = match.group(1), match.group(2)
        quoted = key.startswith('"')
        end = index + 1
        while end < len(lines) and _indent(lines[end]) > indent:
            end += 1
        nodes.append((_unquote(key) if quoted else key, quoted, rest,
                      lines[index + 1:end]))
        index = end
    return nodes


def _node_value(rest, children, indent):
    if rest == 'empty list':
        return []
    if rest == 'empty record':
        return {}
    if rest is not None:
        if children:
            raise ConversionError('multi-line DDN values are not supported')
        return _scalar_value(rest)
    nodes = _nodes(children, indent + 4)
    if nodes and all(key == 'item' and not quoted
                     for key, quoted, _r, _c in nodes):
        return [_node_value(r, c, indent + 4) for _k, _q, r, c in nodes]
    return {key: _node_value(r, c, indent + 4)
            for key, _q, r, c in nodes}


def parse_declarations(text):
    """Parse writer-dialect text into ``[{kind, id, role, props}]``."""
    lines = text.split('\n')
    declarations, index = [], 0
    while index < len(lines):
        line = lines[index]
        if not line.strip() or line.startswith('//') or (
                line.startswith('version ')):
            index += 1
            continue
        match = _DECL.match(line)
        if match is None or index + 1 >= len(lines) or (
                lines[index + 1] != '    with'):
            raise ConversionError(f'unsupported DDN line {line[:60]!r}')
        index += 2
        block = []
        while index < len(lines) and lines[index].startswith(' ' * 8):
            block.append(lines[index])
            index += 1
        props = {key: _node_value(r, c, 8)
                 for key, _q, r, c in _nodes(block, 8)}
        declarations.append({
            'kind': match.group(1), 'id': _unquote(match.group(2)),
            'role': _unquote(match.group(3)) if match.group(3) else None,
            'props': props})
    return declarations


# ---------------------------------------------------------------------------
# DDN snapshot -> BI dashboard document
# ---------------------------------------------------------------------------
def _snapshot_text(snapshot):
    if not isinstance(snapshot, dict) or snapshot.get('format') != (
            DDN_FORMAT):
        raise ConversionError(
            'only ddn-source-workspace@1 snapshots convert; legacy dashboard '
            'sources need an explicit migration first')
    files = snapshot.get('files')
    entry = snapshot.get('entry', 'dashboard.ddn')
    if not isinstance(files, dict) or not isinstance(
            files.get(entry), str):
        raise ConversionError('snapshot has no dashboard source file')
    return files, entry


def ddn_to_dashboard(snapshot, name=None):
    """Return ``{'dashboard': document, 'loss': [...]}`` for a snapshot."""
    files, entry = _snapshot_text(snapshot)
    loss = []
    if len(files) != 1:
        loss.append(_loss('extra_files', 'warning',
                          'only the entry file is converted'))
    declarations = parse_declarations(files[entry])
    feed = next((d for d in declarations if d['kind'] == 'source'), None)
    data = next((d for d in declarations if d['kind'] == 'data'), None)
    if feed is None or data is None or feed['id'] != 'metric_feed' or (
            data['id'] != 'observations'):
        raise ConversionError(
            'not a monitoring dashboard: needs source metric_feed and data '
            'observations')
    channel = feed['props'].get('channel', '')
    if not channel.endswith(_CHANNEL_SUFFIX):
        raise ConversionError('metric_feed channel is not an observations '
                              'channel')
    module = channel[:-len(_CHANNEL_SUFFIX)]
    column_ids = tuple(c.get('id') for c in data['props'].get('columns', []))
    if column_ids != METRIC_COLUMNS:
        raise ConversionError('observations columns are not the metric '
                              'schema')
    observations = [dict(zip(METRIC_COLUMNS, row))
                    for row in data['props'].get('rows', [])]
    views = {d['id']: d for d in declarations if d['kind'] == 'view'}
    known = {'source', 'data', 'view'}
    for declaration in declarations:
        if declaration['kind'] not in known:
            loss.append(_loss(
                'declaration_dropped', 'warning',
                f"{declaration['kind']} {declaration['id']!r} has no "
                'dashboard document equivalent'))
    panel_views = {}
    for ident, declaration in views.items():
        if declaration['role'] != 'table.records@1':
            continue
        options = declaration['props'].get('projection', {}).get(
            'options', {})
        wanted = [item.get('value') for item in options.get('filter', [])
                  if item.get('key') == 'panel' and item.get('op') == 'eq']
        if len(wanted) != 1:
            loss.append(_loss('view_unmapped', 'warning',
                              f'table view {ident!r} has no panel filter'))
            continue
        panel_views[ident] = {'panel_id': wanted[0],
                              'title': declaration['props'].get('title', ''),
                              'columns': options.get('columns', [])}
    pages = [d for d in declarations
             if d['kind'] == 'view' and d['role'] == 'panels.composed@1']
    if not pages:
        raise ConversionError('dashboard has no composed page view')
    tabs, cards, columns_seen, used_cards = [], [], set(), set()
    for page in pages:
        options = page['props'].get('projection', {}).get('options', {})
        columns = options.get('columns', 2)
        columns_seen.add(columns)
        if columns not in (1, 2, 3, 4):
            raise ConversionError(
                f'composed page {page["id"]!r} uses {columns} columns; '
                'the grid supports 1 to 4')
        tab_id = page['id']
        tabs.append({'id': tab_id, 'name': page['props'].get('title',
                                                             tab_id)})
        width = 24 // columns
        for position, panel in enumerate(options.get('panels', [])):
            target = panel.get('target', {}).get('id')
            view = panel_views.get(target)
            if view is None:
                loss.append(_loss(
                    'panel_unmapped', 'warning',
                    f'composed panel {target!r} does not reference a '
                    'filtered table view'))
                continue
            layout = panel.get('layout', {})
            row, column = layout.get('row', position // columns), layout.get(
                'column', position % columns)
            card_id = view['panel_id']
            if not _CARD_ID.match(card_id) or card_id in used_cards:
                card_id = f'card_{len(cards) + 1}'
                loss.append(_loss(
                    'card_id_assigned', 'info',
                    f"panel {view['panel_id']!r} is not a card identifier; "
                    f'card {card_id!r} keeps it as panel_id'))
            used_cards.add(card_id)
            if view['columns'] != [{'id': k, 'label': v}
                                   for k, v in VIEW_COLUMNS]:
                loss.append(_loss('columns_reset', 'info',
                                  f'view {target!r} has custom columns'))
            cards.append({
                'id': card_id, 'tab_id': tab_id, 'type': 'metric_panel',
                'title': panel.get('title') or view['title'],
                'layout': {'x': column * width, 'y': row * CARD_HEIGHT,
                           'w': width, 'h': CARD_HEIGHT},
                'metric_panel': {
                    'panel_id': view['panel_id'],
                    'columns': [{'id': k, 'label': v}
                                for k, v in VIEW_COLUMNS],
                    'rows': [{'id': o['id'], 'measure': o['measure'],
                              'value': o['value'], 'unit': o['unit'],
                              'rate': o['rate']}
                             for o in observations
                             if o['panel'] == view['panel_id']]}})
    if len(columns_seen) > 1:
        loss.append(_loss('mixed_columns', 'warning',
                          'pages use different column counts; the first is '
                          'kept in settings'))
    shown = {c['metric_panel']['panel_id'] for c in cards}
    orphans = sorted({o['panel'] for o in observations} - shown)
    if orphans:
        loss.append(_loss('observations_unreferenced', 'warning',
                          'observations for panels with no card were '
                          'dropped: ' + ', '.join(orphans)))
    dashboard = validate_dashboard({
        'name': name or pages[0]['props'].get('title') or module,
        'tabs': tabs, 'cards': cards,
        'settings': {'monitoring': {
            'module': module, 'channel': channel,
            'columns': next(iter(sorted(columns_seen))) if columns_seen
            else 2,
            'entry': entry, 'view': snapshot.get('view', pages[0]['id'])}},
    })
    return {'dashboard': dashboard, 'loss': loss}


# ---------------------------------------------------------------------------
# BI dashboard document -> DDN snapshot
# ---------------------------------------------------------------------------
def dashboard_to_ddn(dashboard, strict=False):
    """Return ``{'snapshot': ..., 'loss': [...]}`` for a monitoring document.

    ``strict`` turns any dropped content into a :class:`ConversionError`.
    """
    document = validate_dashboard(dashboard)
    monitoring = document['settings'].get('monitoring')
    if monitoring is None:
        raise ConversionError(
            'dashboard has no settings.monitoring binding; only monitoring '
            'dashboards can become DDN sources')
    loss = []
    tab_order = {t['id']: i for i, t in enumerate(document['tabs'])}
    panels, dropped = [], []
    for card in sorted(document['cards'], key=lambda c: (
            tab_order[c['tab_id']], c['layout']['y'], c['layout']['x'])):
        if card['type'] != 'metric_panel':
            dropped.append(card)
            continue
        metric = card['metric_panel']
        panels.append({'id': metric['panel_id'],
                       'title': card['title'] or metric['panel_id'],
                       'rows': metric['rows'], 'tab': card['tab_id'],
                       'layout': card['layout']})
    for card in dropped:
        loss.append(_loss(
            'card_not_representable', 'warning',
            f"{card['type']} card {card['id']!r} has no DDN monitoring "
            'equivalent and was dropped'))
    if document['filters'] or document['cross_filters'] or (
            document['drill_throughs']):
        loss.append(_loss('interaction_dropped', 'warning',
                          'filters, cross-filters and drill-throughs are '
                          'not part of DDN monitoring dashboards'))
    if not panels:
        raise ConversionError('dashboard has no metric_panel cards')
    # The DDN writer fixes two columns, twelve panels per page.
    expected_tabs = [panels[i]['tab'] for i in range(len(panels))]
    pages = [expected_tabs[i:i + PAGE_PANELS]
             for i in range(0, len(expected_tabs), PAGE_PANELS)]
    if any(len(set(page)) != 1 for page in pages) or len(
            document['tabs']) != len(pages):
        loss.append(_loss('pagination_recomputed', 'info',
                          'DDN pages hold twelve panels each; tabs were '
                          'regrouped'))
    off_grid = [p['id'] for index, p in enumerate(panels)
                if (p['layout']['w'], p['layout']['h']) != (12, CARD_HEIGHT)
                or p['layout']['x'] != (index % 2) * 12 or
                p['layout']['y'] != ((index % PAGE_PANELS) // 2) *
                CARD_HEIGHT]
    if off_grid:
        loss.append(_loss('layout_normalized', 'info',
                          'DDN uses a fixed two-column layout; custom '
                          'positions were normalized for: ' +
                          ', '.join(off_grid[:10])))
    if monitoring['columns'] != 2:
        loss.append(_loss('columns_normalized', 'info',
                          'DDN monitoring pages use two columns'))
    if strict and loss:
        raise ConversionError('conversion would lose content: ' + '; '.join(
            item['code'] for item in loss))
    title = document['tabs'][0]['name']
    files = dashboard_panel_files(
        [{'id': p['id'], 'title': p['title'], 'rows': p['rows']}
         for p in panels], title, monitoring['module'])
    view = monitoring['view'] if re.fullmatch(
        r'dashboard(_page_\d+)?', monitoring['view']) else 'dashboard'
    return {'snapshot': {'format': DDN_FORMAT, 'files': files,
                         'entry': 'dashboard.ddn', 'view': view},
            'loss': loss}
