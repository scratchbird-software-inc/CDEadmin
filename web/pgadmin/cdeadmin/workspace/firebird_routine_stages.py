"""Native cycle signatures refuse calls until the real body has been installed."""
from . import firebird_routine_plan as routines

WARNING = ('Mutually dependent new PSQL routines use non-callable signatures before final bodies. '
           'All phases must complete in the same transaction; intermediate definitions are not usable routines.')


def admitted(kind, model):
    return kind in {'procedure', 'function'} and model.get('engine_name') is None and model.get('entrypoint') is None


def parts(kind, model):
    if not admitted(kind, model):
        raise ValueError('Only new standalone native PSQL routines admit signature staging')
    # Firebird 5 evlSetContext accepts only USER_SESSION/USER_TRANSACTION.
    # This deliberately invalid namespace raises before a temporary body can
    # fabricate output or write a context value, including calls by DDL triggers.
    body = "BEGIN RDB$SET_CONTEXT('SCRATCHROBIN_INCOMPLETE_SCHEMA', 'routine', NULL);"
    if kind == 'function':
        body += ' RETURN NULL;'
    body += ' END'
    signature = {**model, 'metadata_source': body}
    return [routines.statements(kind, None, signature)[0]], routines.statements(kind, signature, model)


def break_cycle(pending, operations):
    candidates = {key for key in pending if operations[key]['operation'] == 'create'
        and not operations[key].get('signature_first') and admitted(operations[key]['kind'], operations[key]['after'])}
    affected = {key for key in candidates if pending[key] & candidates}
    if not affected:
        return False
    for key in affected:
        operation = operations[key]
        primary, body = parts(operation['kind'], operation['after'])
        # Preserve the object COMMENT generated by the main planner; parameter
        # comments belong to the complete final declaration generated above.
        object_prefix = 'COMMENT ON ' + operation['kind'].upper() + ' '
        comments = [statement for statement in operation['statements'][1:]
                    if statement.startswith(object_prefix) and not statement.startswith(object_prefix + 'PARAMETER ')]
        operation['statements'] = primary
        operation['deferred_statements'] = body + comments
        operation['signature_first'] = True
        pending[key].difference_update(candidates)
    return True
