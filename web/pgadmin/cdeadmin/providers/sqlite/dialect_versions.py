"""Versioned SQLite dialect tables (owner direction, 2026-10-29).

``sqlite_dialect_versions.json`` is generated by
``tools/reference_engine_demos/merge_sqlite_dialect_versions.py`` from one
inventory per tracked SQLite version. A running SQLite is served from the
greatest tracked version at or below it: anything a later, untracked release
added is not offered until that release is tracked. A runtime newer than
every tracked version uses the newest table and is flagged.

Runtime catalogs (functions, pragmas) were collected from builds that share
the reference library's compile options. An installation built with fewer
options can lack entries listed here; its own runtime probe is the authority
for that installation.
"""

import copy
import json
from functools import lru_cache
from pathlib import Path

from .provider import PROFILE

TABLE = Path(__file__).with_name('sqlite_dialect_versions.json')


def _version(text):
    return tuple(int(part) for part in str(text).split('.'))


@lru_cache(maxsize=1)
def versioned_table():
    document = json.loads(TABLE.read_text(encoding='utf-8'))
    if document.get('schema') != 'cdeadmin.engine-dialect-versions.v1':
        raise ValueError('SQLite versioned dialect table has another schema')
    if document.get('reference_version') != PROFILE.exact_version:
        raise ValueError(
            'SQLite versioned dialect table has another reference')
    return document


def table_version_for(runtime_version):
    """Return (tracked version, newer_than_tracked) for a running SQLite."""
    if not PROFILE.accepts_runtime_version(runtime_version):
        raise ValueError(
            f'SQLite {runtime_version} is outside the supported '
            f'{PROFILE.version_requirement} range')
    tracked = versioned_table()['tracked_versions']
    observed = _version(runtime_version)
    eligible = [value for value in tracked if _version(value) <= observed]
    if not eligible:
        raise ValueError(
            f'no tracked SQLite table covers {runtime_version}; the oldest '
            f'tracked version is {tracked[0]}')
    selected = max(eligible, key=_version)
    return selected, observed > _version(max(tracked, key=_version))


def inventory_for(runtime_version):
    """Rebuild the dialect inventories that apply to a running SQLite."""
    selected, _newer = table_version_for(runtime_version)
    result = {}
    for name, items in versioned_table()['inventories'].items():
        rows = []
        for item in items:
            if selected not in item['present_in']:
                continue
            record = copy.deepcopy(item.get('record_by_version', {}).get(
                selected, item['record']))
            record['item_id'] = item['item_ids'][selected]
            rows.append(record)
        rows.sort(key=lambda row: row['item_id'])
        result[name] = rows
    return result


def task_proven(task_id, runtime_version):
    """Whether a dialect task executed live on the runtime's table version.

    The proof covers the drafts the live qualification exercised on that
    tracked version; untracked versions inherit the nearest older proof.
    """
    try:
        selected, _newer = table_version_for(runtime_version)
    except ValueError:
        return False
    proof = versioned_table().get('task_proof', {}).get(selected)
    return bool(proof) and task_id in proof['proven_tasks']


def function_available(name, runtime_version):
    """Whether a built-in function name exists in the runtime's table."""
    selected, _newer = table_version_for(runtime_version)
    return any(
        entry['function_name'] == name and selected in entry['present_in']
        for entry in versioned_table()['derived']['function_names'])
