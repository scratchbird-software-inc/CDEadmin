#!/usr/bin/env python3
"""Every refusal the PostgreSQL provider can raise, read from its source (Decision 22).

A refusal is an exception raised with a message: ``PostgreSQLNativeAdminError``, ``_refuse`` and
``PostgreSQLProviderError``. The first argument is one of

* a string literal: fixed text with no user data, registered as it stands in
  ``providers/postgresql/refusal_literals.json``;
* an f-string or a built string: it may hold a value the user typed or native tool output, so it is
  matched by a rule in ``refusal_codes.RULES`` and shown as the catalog's sentence for the rule;
* anything else (a name, a call, an attribute): the message of another exception passed on, which is
  classified where it began.

``python3 tools/refusal_inventory.py --write`` regenerates the literal list; ``--check`` fails when it
is out of date. ``test_refusal_reasons.py`` runs the same check, so a new refusal that is neither
registered nor matched by a rule fails the build.
"""
import ast
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROVIDER = ROOT / 'web/pgadmin/cdeadmin/providers/postgresql'
LITERALS = PROVIDER / 'refusal_literals.json'
# Raised while compiling or planning; PostgreSQLStatementRejected is an apply-time rejection with its own
# contract (the server's own words, 2026-11-11).
RAISED = {'PostgreSQLNativeAdminError', 'PostgreSQLProviderError', '_refuse'}


def _template(node):
    """('literal'|'dynamic'|'forwarded', text) for the message argument of a refusal."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return 'literal', node.value
    if isinstance(node, ast.JoinedStr):
        return 'dynamic', ''.join(part.value if isinstance(part, ast.Constant) else '{}' for part in node.values)
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        (left_kind, left), (right_kind, right) = _template(node.left), _template(node.right)
        if left_kind == right_kind == 'literal':
            return 'literal', left + right
        return 'dynamic', (left if left_kind != 'forwarded' else '{}') + (right if right_kind != 'forwarded' else '{}')
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Mod):
        kind, left = _template(node.left)
        return ('dynamic', left) if kind != 'forwarded' else ('forwarded', '')
    return 'forwarded', ''


def sites():
    """[{file, line, kind, text}] for every refusal that carries its own message."""
    found = []
    for path in sorted(PROVIDER.glob('*.py')):
        for node in ast.walk(ast.parse(path.read_text(encoding='utf-8'))):
            if not isinstance(node, ast.Call):
                continue
            function = node.func
            name = function.id if isinstance(function, ast.Name) else function.attr if isinstance(function, ast.Attribute) else None
            if name in RAISED and node.args:
                kind, text = _template(node.args[0])
                if kind != 'forwarded':
                    found.append({'file': path.name, 'line': node.lineno, 'kind': kind, 'text': text})
    return found


def literals():
    return sorted({site['text'] for site in sites() if site['kind'] == 'literal'})


def dynamic_templates():
    return sorted({site['text'] for site in sites() if site['kind'] == 'dynamic'})


def document():
    return {'schema': 'cdeadmin.pg-refusal-literals.v1',
            'notes': 'Generated by tools/refusal_inventory.py --write. Each message is fixed text in the PostgreSQL provider '
                     'source, with no user data; it may be shown to the user as it stands (Decision 22).',
            'messages': literals()}


def main(argv):
    text = json.dumps(document(), indent=1, ensure_ascii=False) + '\n'
    if '--write' in argv:
        LITERALS.write_text(text, encoding='utf-8')
        print(f'wrote {len(document()["messages"])} messages')
        return 0
    if '--check' in argv:
        current = LITERALS.read_text(encoding='utf-8') if LITERALS.exists() else ''
        if current != text:
            print('refusal_literals.json is out of date; run tools/refusal_inventory.py --write')
            return 1
        return 0
    print(f'{len(literals())} literal messages, {len(dynamic_templates())} dynamic templates')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
