def test_primary_key_nullability_cannot_be_removed():
    base = catalog(not_null=1)
    base['rows']['constraint:T/PK'] = {'kind': 'constraint', 'resource_id': 'constraint:T/PK',
        'name': 'PK', 'path': ['T', 'PK'], 'system': 'false',
        'native': {'constraint_type': 'PRIMARY KEY', 'index_name': 'PK_INDEX'}}
    base['rows']['index:T/PK_INDEX'] = {'kind': 'index', 'resource_id': 'index:T/PK_INDEX',
        'name': 'PK_INDEX', 'path': ['T', 'PK_INDEX'], 'system': 'true',
        'native': {'segments': [{'field_name': 'C', 'position': 0}]}}
    desired = deepcopy(base); column_row(desired)['native']['not_null'] = None
    result = build_plan(base, desired, base)
    assert result['status'] == 'blocked'
    assert any('DROP NOT NULL' in item['reason'] for item in result['blockers'])


