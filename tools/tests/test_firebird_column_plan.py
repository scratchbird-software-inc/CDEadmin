def test_new_column_uses_full_native_definition_and_position():
    base = catalog(); desired = deepcopy(base)
    identity = catalog_resource_id('column', ['T'], 'Added"')
    new = deepcopy(column_row(base))
    new.update(resource_id=identity, name='Added"', path=['T', 'Added"'])
    new['native'].update(position=1, description='new field', ddl='DROP DATABASE')
    desired['rows'][identity] = new
    result = build_plan(base, desired, base)
    assert result['status'] == 'review-ready', result['blockers']
    assert result['operations'][0]['statements'] == [
        'ALTER TABLE "T" ADD "Added""" INTEGER',
        'COMMENT ON COLUMN "T"."Added""" IS \'new field\'']
    assert result['operations'][0]['deferred_statements'] == ['ALTER TABLE "T" ALTER COLUMN "Added""" POSITION 2']
    new['native']['position'] = 9
    assert build_plan(base, desired, base)['status'] == 'blocked'


def test_multiple_column_positions_are_deferred_and_sorted_independent_of_names():
    base = catalog(); desired = deepcopy(base)
    for name, position in [('A_NEW', 2), ('Z_NEW', 1)]:
        row = deepcopy(column_row(base)); identity = catalog_resource_id('column', ['T'], name)
        row.update(name=name, path=['T', name], resource_id=identity)
        row['native']['position'] = position
        desired['rows'][identity] = row
    result = build_plan(base, desired, base)
    assert result['status'] == 'review-ready', result['blockers']
    assert [sql for operation in result['operations'] for sql in operation['deferred_statements']] == [
        'ALTER TABLE "T" ALTER COLUMN "Z_NEW" POSITION 2',
        'ALTER TABLE "T" ALTER COLUMN "A_NEW" POSITION 3']
    desired['rows'][catalog_resource_id('column', ['T'], 'Z_NEW')]['native']['position'] = 2
    assert build_plan(base, desired, base)['status'] == 'blocked'


def test_new_table_repeated_column_definition_is_emitted_once_and_guarded():
    wanted = catalog(); base = deepcopy(wanted)
    del base['rows']['table:T']
    del base['rows'][catalog_resource_id('column', ['T'], 'C')]
    plan = build_plan(base, wanted, base)
    assert plan['status'] == 'review-ready', plan['blockers']
    child = next(item for item in plan['operations'] if item['kind'] == 'column')
    assert child['embedded_column_definition'] and child['statements'] == [] and child['deferred_statements'] == []
    assert plan['script'].count('"C" INTEGER') == 1
    assert child['native_preconditions'][child['resource_id']] is None
    column_row(wanted)['native']['field_type'] = 16
    assert build_plan(base, wanted, base)['status'] == 'blocked'


def test_integer_type_change_is_native_alter_and_checks_complete_semantics():
    base = catalog(); wanted = catalog(field_type=16, field_length=8)
    plan = build_plan(base, wanted, base)
    assert plan['status'] == 'review-ready', plan['blockers']
    assert plan['operations'][0]['statements'] == ['ALTER TABLE "T" ALTER COLUMN "C" TYPE BIGINT']
    assert build_plan(base, wanted, wanted)['status'] == 'no-op'
    assert build_plan(base, catalog(field_type=False), base)['status'] == 'blocked'
    assert build_plan(base, catalog(field_type=16, field_sub_type=1, field_precision=4), base)['status'] == 'blocked'


