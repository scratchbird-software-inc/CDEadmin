"""CockroachDB table create/alter compilation and the readers behind it."""
import sys
from pathlib import Path
from types import ModuleType

import pytest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'web'))
if 'pgadmin' not in sys.modules:
    package = ModuleType('pgadmin')
    package.__path__ = [str(ROOT / 'web/pgadmin')]
    sys.modules['pgadmin'] = package

from pgadmin.cdeadmin.providers.cockroachdb import tables  # noqa: E402
from pgadmin.cdeadmin.providers.cockroachdb.provider import (  # noqa: E402
    ADMINISTRATION,
)
from pgadmin.cdeadmin.sdk import RelationalClientError  # noqa: E402

ROUTE = {'host': '127.0.0.1'}


def plan(operation, draft, target=None):
    planned = ADMINISTRATION.plan({
        'resource_kind': 'table', 'operation_id': operation,
        'target_resource': target, 'draft': draft, '_provider_route': ROUTE})
    compiled = planned['provider_payload']['compiled']
    return ([item['source'] for item in compiled['statements']],
            compiled.get('warnings', []))


def test_parse_create_reads_on_update_and_families_with_quoted_names():
    statement = (
        'CREATE TABLE s."we,ird" (\n\tid INT8 NOT NULL,\n'
        '\t"x y" INT8 NULL DEFAULT 1:::INT8 ON UPDATE 1:::INT8,\n'
        '\tCONSTRAINT "we,ird_pkey" PRIMARY KEY (id ASC),\n'
        '\tFAMILY "f 1" (id, "x y"),\n\tFAMILY f2 (z)\n'
        ') WITH (schema_locked = true);')
    assert tables.parse_create(statement) == (
        ('s', 'we,ird'), {'x y': '1'},
        [{'name': 'f 1', 'columns': ['id', 'x y']},
         {'name': 'f2', 'columns': ['z']}])


def test_parse_reloptions():
    assert tables.parse_reloptions([
        "ttl='on'", "ttl_expire_after='1 day':::INTERVAL",
        "ttl_job_cron='@daily'", 'schema_locked=true']) == {
        'ttl': 'on', 'ttl_expire_after': '1 day', 'ttl_job_cron': '@daily',
        'schema_locked': 'true'}


def test_create_carries_cockroachdb_column_options_families_and_ttl():
    sources, _ = plan('create', {
        'name': 'orders', 'parent': 'public',
        'columns': [
            {'name': 'id', 'type': 'INT8', 'nullable': False},
            {'name': 'seq', 'type': 'INT8', 'identity': 'BY DEFAULT',
             'family': 'hot'},
            {'name': 'touched', 'type': 'TIMESTAMPTZ',
             'default': 'now()', 'on_update': 'now()', 'not_visible': True,
             'family': 'hot', 'comment': "it's"},
            {'name': 'twice', 'type': 'INT8', 'generated_kind': 'VIRTUAL',
             'generated_expression': 'id * 2'},
        ],
        'primary_key': [{'name': 'orders_pk', 'columns': ['id']}],
        'foreign_keys': [{'name': 'fk', 'columns': ['seq'],
                          'references_table': ['public', 'p'],
                          'references_columns': ['k'],
                          'on_delete': 'CASCADE'}],
        'ttl_expire_after': '30 days', 'comment': 'orders'})
    assert sources == [
        'CREATE TABLE "public"."orders" ("id" INT8 NOT NULL, '
        '"seq" INT8 GENERATED BY DEFAULT AS IDENTITY, '
        '"touched" TIMESTAMPTZ NOT VISIBLE DEFAULT now() ON UPDATE now(), '
        '"twice" INT8 AS (id * 2) VIRTUAL, '
        'CONSTRAINT "orders_pk" PRIMARY KEY ("id"), '
        'CONSTRAINT "fk" FOREIGN KEY ("seq") REFERENCES "public"."p" ("k") '
        'ON DELETE CASCADE, '
        'FAMILY "hot" ("seq", "touched")) '
        "WITH (ttl_expire_after = '30 days')",
        'COMMENT ON TABLE "public"."orders" IS \'orders\'',
        'COMMENT ON COLUMN "public"."orders"."touched" IS \'it\'\'s\'',
    ]


@pytest.mark.parametrize('column, reason', [
    ({'generated_kind': 'STORED', 'generated_expression': 'id',
      'default': '1'}, 'no default, identity'),
    ({'identity': 'ALWAYS', 'default': '1'}, 'no default expression'),
    ({'generated_kind': 'VIRTUAL', 'generated_expression': 'id',
      'family': 'f'}, 'cannot belong to a family'),
    ({'identity': 'SOMETIMES'}, 'identity must be one of'),
])
def test_create_refuses_what_cockroachdb_refuses(column, reason):
    with pytest.raises(RelationalClientError, match=reason):
        plan('create', {'name': 't', 'columns': [
            {'name': 'c', 'type': 'INT8', **column}]})


TARGET = {
    'resource_id': 'table:public:t', 'resource_kind': 'table',
    'display_name': 't', 'display_path': ['public', 't'],
    'native': {
        'schema_locked': True, 'comment': None,
        'ttl_expire_after': '1 day', 'ttl_expiration_expression': None,
        'ttl_job_cron': None,
        'constraints': [
            {'name': 't_pkey', 'kind': 'PRIMARY KEY', 'columns': ['id']},
            {'name': 'uq_a', 'kind': 'UNIQUE', 'columns': ['a']},
            {'name': 'ck', 'kind': 'CHECK', 'expression': 'a > 0'},
        ]},
}


def test_alter_orders_changes_and_diffs_only_the_grids_sent():
    sources, warnings = plan('alter', {
        'rename_columns': [{'from': 'a', 'to': 'b'}],
        'alter_columns': [{'name': 'b', 'changes': {
            'type': 'INT4', 'default': None, 'nullable': False,
            'not_visible': True, 'comment': 'x'}}],
        'add_columns': [{'name': 'n', 'type': 'INT8', 'family': 'f3'}],
        # Unique grid sent: uq_a gone, uq_n new. Check grid not sent: kept.
        'unique_constraints': [{'name': 'uq_n', 'columns': ['n']}],
        'primary_key': [{'name': 't_pkey', 'columns': ['id', 'b']}],
        'ttl_expire_after': '', 'comment': 'now commented',
    }, TARGET)
    table = '"public"."t"'
    assert sources == [
        f'DROP INDEX {table}@"uq_a" CASCADE',
        f'ALTER TABLE {table} RENAME COLUMN "a" TO "b"',
        f'ALTER TABLE {table} ALTER COLUMN "b" TYPE INT4',
        f'ALTER TABLE {table} ALTER COLUMN "b" DROP DEFAULT',
        f'ALTER TABLE {table} ALTER COLUMN "b" SET NOT NULL',
        f'ALTER TABLE {table} ALTER COLUMN "b" SET NOT VISIBLE',
        f'COMMENT ON COLUMN {table}."b" IS \'x\'',
        f'ALTER TABLE {table} ADD COLUMN "n" INT8 CREATE IF NOT EXISTS '
        'FAMILY "f3"',
        f'ALTER TABLE {table} ALTER PRIMARY KEY USING COLUMNS ("id", "b")',
        f'ALTER TABLE {table} ADD CONSTRAINT "uq_n" UNIQUE ("n")',
        f'ALTER TABLE {table} RESET (ttl)',
        f'COMMENT ON TABLE {table} IS \'now commented\'',
    ]
    assert 'UNIQUE index' in warnings[0]


def test_dropping_identity_unlocks_a_schema_locked_table():
    sources, _ = plan('alter', {'alter_columns': [
        {'name': 'seq', 'changes': {'identity': None}}]}, TARGET)
    assert sources == [
        'ALTER TABLE "public"."t" SET (schema_locked = false)',
        'ALTER TABLE "public"."t" ALTER COLUMN "seq" DROP IDENTITY',
        'ALTER TABLE "public"."t" SET (schema_locked = true)']


def test_unchanged_constraint_rows_send_nothing():
    with pytest.raises(RelationalClientError, match='nothing to change'):
        plan('alter', {'check_constraints': [
            {'name': 'ck', 'expression': '(a > 0)'}]}, TARGET)


@pytest.mark.parametrize('draft, reason', [
    ({'alter_columns': [{'name': 'a', 'changes': {'unique': True}}]},
     'use the Unique grid'),
    ({'alter_columns': [{'name': 'a', 'changes': {'family': 'x'}}]},
     'another family'),
    ({'alter_columns': [{'name': 'a', 'changes': {
        'generated_kind': 'STORED'}}]}, 'only when added'),
    ({'primary_key': []}, 'exactly one primary key'),
    ({'ttl_expire_after': '', 'ttl_job_cron': '@daily'},
     'needs an expiry'),
    ({'bogus': 1}, 'unknown table change'),
])
def test_alter_refuses_by_name(draft, reason):
    with pytest.raises(RelationalClientError, match=reason):
        plan('alter', draft, TARGET)


def test_array_column_types():
    statements, _ = plan('create', {
        'name': 'a', 'parent': 'public', 'columns': [
            {'name': 'x', 'type': 'INT8[]'},
            {'name': 'y', 'type': 'STRING [3]'}]})
    assert '"x" INT8[]' in statements[0] and '"y" STRING[3]' in \
        statements[0]
    with pytest.raises(RelationalClientError, match='at most 1 dimension'):
        plan('create', {'name': 'a', 'parent': 'public', 'columns': [
            {'name': 'y', 'type': 'STRING[][]'}]})
