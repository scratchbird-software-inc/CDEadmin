"""Disposable-fixture qualification helper for native column order."""
from pgadmin.cdeadmin.providers.firebird.provider import ADMINISTRATION, _resources
from pgadmin.cdeadmin.sdk.relational import RelationalClientError
from pgadmin.cdeadmin.providers.firebird.error_diagnostics import status_codes


def qualify(connection, client, route):
    def sql(source):
        with connection.cursor() as cursor:
            cursor.execute(source)
            return cursor.fetchall() if cursor.description else []
    name = 'Order:ü"'
    quoted = '"Order:ü"""'
    sql('CREATE TABLE ' + quoted + ' (A INTEGER PRIMARY KEY, B VARCHAR(20), '
        'C COMPUTED BY (A+1), D INTEGER GENERATED BY DEFAULT AS IDENTITY)')
    connection.commit()
    sql('INSERT INTO ' + quoted + " (A, B) VALUES (1, 'retained')")
    connection.commit()
    def inspect():
        row = next(item for item in _resources(connection, {})
                   if item['resource_kind'] == 'table' and item['display_name'] == name)
        connection.rollback()
        return row
    before = inspect()
    request = {'resource_kind': 'table', 'operation_id': 'reorder_columns',
        '_provider_route': route, 'target_resource': before,
        'draft': {'column_order': ['D', 'C', 'B', 'A']}}
    plan = ADMINISTRATION.plan(request)
    # Borrowed transaction: POSITION statements stage, rollback restores order.
    staged = ADMINISTRATION.apply(client, plan, connection=connection)
    assert staged['commit_requested'] is False
    connection.rollback()
    assert inspect()['native']['column_order'] == ['A', 'B', 'C', 'D']
    # Owned path commits once and native rediscovery shows the selected order.
    committed = ADMINISTRATION.apply(client, plan)
    assert committed['commit_requested'] is True
    actual = inspect()
    assert actual['native']['column_order'] == ['D', 'C', 'B', 'A']
    assert actual['native']['relation_id'] == before['native']['relation_id']
    assert sql('SELECT A, B, C, D FROM ' + quoted) == [(1, 'retained', 2, 1)]
    connection.rollback()
    # Reusing the old compiled order must stop before another move.
    try:
        ADMINISTRATION.apply(client, plan)
    except RelationalClientError:
        pass
    else:
        raise AssertionError('Stale table order was not refused')
    assert inspect()['native']['column_order'] == ['D', 'C', 'B', 'A']
    import secrets
    from types import SimpleNamespace
    from pgadmin.cdeadmin.providers.firebird.provider import _create_client
    from pgadmin.cdeadmin.security.secrets import SecretLease
    username, password = 'ORDER_RESTRICTED', secrets.token_urlsafe(24)
    sql("CREATE USER " + username + " PASSWORD '" + password + "'")
    connection.commit()
    try:
        sql('GRANT SELECT ON ' + quoted + ' TO USER ' + username)
        connection.commit()
        restricted = _create_client(SimpleNamespace(acquire_secret=lambda *_: SecretLease(password)))
        restricted_plan = ADMINISTRATION.plan({**request,
            '_provider_route': {**route, 'user': username}, 'target_resource': inspect(),
            'draft': {'column_order': ['A', 'B', 'C', 'D']}})
        try:
            ADMINISTRATION.apply(restricted, restricted_plan)
        except RelationalClientError as error:
            denied = list(status_codes(error))
            assert 335544352 in denied, denied
        else:
            raise AssertionError('SELECT-only account reordered table columns')
        assert not restricted._connections
        assert inspect()['native']['column_order'] == ['D', 'C', 'B', 'A']
    finally:
        sql('DROP USER ' + username)
        connection.commit()
    return {'borrowed_rollback_verified': True, 'owned_commit_verified': True,
            'data_and_identity_preserved': True, 'stale_order_refused': True,
            'permission_denial_codes': denied, 'temporary_user_removed': True,
            'before': before['native']['column_order'], 'after': actual['native']['column_order'],
            'preview': plan['command_preview']}
