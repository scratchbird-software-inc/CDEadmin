#!/usr/bin/env python3
"""Native view insertion without keys and nested/trigger projection edits."""
import argparse
import json
import secrets
from pathlib import Path
from types import SimpleNamespace

from tools.cdeadmin_firebird_stream_gate import (
    _create_client, _route_arguments,
)
from tools.cdeadmin_firebird_local_fixture import run_local
from tools.cdeadmin_firebird_admin_mapping_gate import ADMINISTRATION
from pgadmin.cdeadmin.providers.firebird.temporal_arrays import cursor
from pgadmin.cdeadmin.sdk.relational import RelationalClientError


def qualify(native, admin, route, accounts, evidence, root):
    user, password = accounts['Srp'][0]
    selected = dict(route, user=user, database=str(root / 'views.fdb'))
    client = _create_client(SimpleNamespace(acquire_secret=None))
    connection = native.create_database(
        password=password, **_route_arguments(selected, native))
    client._connections.append(connection)
    checks, failures = [], []

    def sql(handle, source, parameters=()):
        with cursor(handle) as query:
            try:
                query.execute(source, parameters)
            except native.DatabaseError as error:
                (evidence / 'native-error.json').write_text(json.dumps({
                    'source': source, 'gds_codes': list(error.gds_codes),
                    'message': str(error)}, indent=2))
                raise
            return query.fetchall() if query.description else None

    def counts(handle):
        return [sql(handle, f'SELECT COUNT(*) FROM {name}')[0][0]
                for name in ('BASE_ROWS', 'LOOKUP_ROWS', 'DUP_ROWS')]

    def request(name):
        return {'_provider_route': selected, 'session_id': 'views-'+name,
                'resource_kind': 'view', 'target_resource': {
                    'resource_kind': 'view', 'display_path': [name]}}

    def page(name):
        return ADMINISTRATION.read_rows(client, request(name),
                                        connection=connection)

    def apply(name, operation, draft):
        plan = ADMINISTRATION.plan({**request(name), 'operation_id': operation,
                                    'draft': draft})
        return ADMINISTRATION.apply(client, plan, connection=connection)

    try:
        for ddl in (
                'CREATE TABLE BASE_ROWS (ID INTEGER GENERATED BY DEFAULT AS '
                'IDENTITY PRIMARY KEY, V INTEGER DEFAULT 7)',
                'CREATE TABLE LOOKUP_ROWS (ID INTEGER PRIMARY KEY, W INTEGER)',
                'CREATE TABLE DUP_ROWS (V INTEGER DEFAULT 7)',
                'CREATE TABLE SIDE_WORK (V INTEGER)',
                'CREATE SEQUENCE VIEW_IDS START WITH 1000'):
            sql(connection, ddl)
        connection.commit()
        for ddl in (
                'CREATE VIEW DIRECT_VIEW AS SELECT ID AS K, V AS VAL0 '
                'FROM BASE_ROWS WHERE V>0 WITH CHECK OPTION',
                'CREATE VIEW NESTED_VIEW AS SELECT K AS KEY_ID, VAL0 AS VAL '
                'FROM DIRECT_VIEW',
                'CREATE VIEW TRIGGER_VIEW AS SELECT ID,V FROM BASE_ROWS',
                'CREATE VIEW KEYLESS_VIEW AS SELECT V FROM DUP_ROWS',
                'CREATE VIEW NESTED_KEYLESS AS SELECT V FROM KEYLESS_VIEW',
                'CREATE VIEW JOINED_VIEW AS SELECT B.ID,B.V,L.W '
                'FROM BASE_ROWS B JOIN LOOKUP_ROWS L ON B.ID=L.ID',
                'CREATE VIEW AGG_VIEW AS SELECT SUM(V) AS V FROM BASE_ROWS'):
            sql(connection, ddl)
            connection.commit()
        for ddl in (
                'CREATE TRIGGER TV_BI FOR TRIGGER_VIEW ACTIVE BEFORE INSERT '
                'AS BEGIN IF (NEW.ID IS NULL) THEN NEW.ID=GEN_ID(VIEW_IDS,1); '
                'INSERT INTO BASE_ROWS(ID,V) VALUES(NEW.ID,NEW.V); END',
                'CREATE TRIGGER TV_BU FOR TRIGGER_VIEW ACTIVE BEFORE UPDATE '
                'AS BEGIN UPDATE BASE_ROWS SET V=NEW.V WHERE ID=OLD.ID; END',
                'CREATE TRIGGER TV_BD FOR TRIGGER_VIEW ACTIVE BEFORE DELETE '
                'AS BEGIN DELETE FROM BASE_ROWS WHERE ID=OLD.ID; END',
                'CREATE TRIGGER JV_BI FOR JOINED_VIEW ACTIVE BEFORE INSERT '
                'AS BEGIN IF (NEW.ID IS NULL) THEN NEW.ID=GEN_ID(VIEW_IDS,1); '
                'INSERT INTO BASE_ROWS(ID,V) VALUES(NEW.ID,NEW.V); '
                'INSERT INTO LOOKUP_ROWS VALUES(NEW.ID,NEW.W); END',
                'CREATE TRIGGER AV_BI FOR AGG_VIEW ACTIVE BEFORE INSERT '
                'AS BEGIN INSERT INTO BASE_ROWS(V) VALUES(NEW.V); END'):
            sql(connection, ddl)
        connection.commit()
        shapes = (
            ('DIRECT_VIEW', {'K': 101, 'VAL0': 11}, [1, 0, 0]),
            ('NESTED_VIEW', {'KEY_ID': 102, 'VAL': 12}, [1, 0, 0]),
            ('TRIGGER_VIEW', {'V': 13}, [1, 0, 0]),
            ('KEYLESS_VIEW', {'V': 14}, [0, 0, 1]),
            ('NESTED_KEYLESS', {'V': 15}, [0, 0, 1]),
            ('JOINED_VIEW', {'V': 16, 'W': 17}, [1, 1, 0]),
            ('AGG_VIEW', {'V': 18}, [1, 0, 0]),
        )
        for name, values, expected in shapes:
            for mode in ('values', 'defaults'):
                case = name+':'+mode
                try:
                    before = counts(connection)
                    default_error = None
                    if mode == 'defaults':
                        try:
                            sql(connection, f'INSERT INTO {name} '
                                'DEFAULT VALUES')
                        except native.DatabaseError as error:
                            default_error = set(error.gds_codes)
                        finally:
                            connection.rollback()
                    current = page(name)
                    assert 'insert' in current['row_operations']
                    if name in ('KEYLESS_VIEW', 'NESTED_KEYLESS'):
                        assert current['editable']
                        assert current['identity_policy'] == (
                            'provider-native-db-key-and-original-values')
                    if name in ('JOINED_VIEW', 'AGG_VIEW'):
                        assert not current['editable']
                        assert current['identity_policy'] == (
                            'provider-view-insert-without-row-identity')
                    token = current['insert_identity_token']
                    assert token
                    if mode == 'defaults':
                        assert current['insert_default_values']
                    try:
                        apply(name, 'insert', {
                            'values': values if mode == 'values' else {},
                            'options': {'identity_token': token}})
                    except RelationalClientError as error:
                        if default_error is None:
                            raise
                        assert set(error.gds_codes) == default_error
                        assert counts(connection) == before
                        checks.append({'case': case,
                                       'native_default_refusal':
                                           sorted(default_error),
                                       'passed': True})
                        continue
                    assert default_error is None
                    assert counts(connection) == [a+b for a, b in
                                                  zip(before, expected)]
                    with native.connect(password=password, **_route_arguments(
                            selected, native)) as observer:
                        assert counts(observer) == before
                    connection.rollback()
                    assert counts(connection) == before
                    checks.append({'case': case, 'passed': True,
                                   'native_trigger_effects': True,
                                   'explicit_rollback': True})
                except Exception as error:
                    failures.append({'case': case,
                                     'type': type(error).__name__,
                                     'detail': str(error).replace(
                                         password, '<redacted>')})
                finally:
                    connection.rollback()
        for name, field in (('NESTED_VIEW', 'VAL'), ('TRIGGER_VIEW', 'V')):
            try:
                current = page(name)
                values = {field: 21}
                if name == 'NESTED_VIEW':
                    values['KEY_ID'] = 201
                apply(name, 'insert', {'values': values, 'options': {
                    'identity_token': current['insert_identity_token']}})
                current = page(name)
                assert {'update', 'delete'} <= set(current['row_operations'])
                apply(name, 'update', {'selector': {'identity_token':
                      current['rows'][0]['identity_token']},
                    'changes': {field: 22}})
                current = page(name)
                assert current['rows'][0]['values'][field] == 22
                apply(name, 'delete', {'selector': {'identity_token':
                      current['rows'][0]['identity_token']}})
                assert not page(name)['rows']
                checks.append({'case': name+':update-delete', 'passed': True})
            except Exception as error:
                failures.append({'case': name+':update-delete',
                                 'type': type(error).__name__,
                                 'detail': str(error).replace(
                                     password, '<redacted>')})
            finally:
                connection.rollback()
        sql(connection, 'INSERT INTO SIDE_WORK VALUES(9)')
        current = page('NESTED_VIEW')
        transaction = connection.main_transaction.info.id
        try:
            apply('NESTED_VIEW', 'insert', {
                'values': {'KEY_ID': 301, 'VAL': -1}, 'options': {
                    'identity_token': current['insert_identity_token']}})
        except RelationalClientError as error:
            assert {335544558, 335544842} & set(error.gds_codes)
        else:
            raise AssertionError('Nested CHECK OPTION was bypassed')
        assert connection.main_transaction.info.id == transaction
        assert sql(connection, 'SELECT V FROM SIDE_WORK') == [(9,)]
        assert counts(connection) == [0, 0, 0]
        connection.rollback()
        checks.append({'case': 'nested-check-option-preserves-side-work',
                       'passed': True})
        limited_user = 'OWNED_VIEW_LIMITED'
        limited_password = secrets.token_urlsafe(24)
        # This is the disposable fixture's security database, not the source
        # runtime. Never send authentication DDL through the diagnostic helper.
        admin.execute_immediate(
            "CREATE USER " + limited_user + " PASSWORD '" +
            limited_password + "' USING PLUGIN Srp")
        admin.commit()
        sql(connection, 'GRANT SELECT,INSERT,UPDATE,DELETE ON NESTED_VIEW '
            'TO USER ' + limited_user)
        connection.commit()
        limited_route = dict(selected, user=limited_user)
        for permitted in (True, False):
            limited = native.connect(password=limited_password,
                                     **_route_arguments(limited_route, native))
            try:
                limited_request = {**request('NESTED_VIEW'),
                                   '_provider_route': limited_route,
                                   'session_id': 'limited-view'}
                current = ADMINISTRATION.read_rows(
                    client, limited_request, connection=limited)
                if permitted:
                    assert 'insert' in current['row_operations']
                    with limited.cursor() as query:
                        try:
                            statement = query.prepare(
                                'INSERT INTO BASE_ROWS(V) VALUES(?)')
                        except native.DatabaseError:
                            pass
                        else:
                            statement.free()
                            raise AssertionError('Base DML was granted')
                    plan = ADMINISTRATION.plan({
                        **limited_request, 'operation_id': 'insert', 'draft': {
                            'values': {'KEY_ID': 401, 'VAL': 31}, 'options': {
                                'identity_token':
                                    current['insert_identity_token']}}})
                    ADMINISTRATION.apply(client, plan, connection=limited)
                    with limited.cursor() as query:
                        query.execute('SELECT VAL FROM NESTED_VIEW '
                                      'WHERE KEY_ID=401')
                        assert query.fetchone()[0] == 31
                    limited.rollback()
                else:
                    assert 'insert' not in current['row_operations']
                    assert current['insert_identity_token'] is None
                    assert {'update', 'delete'} <= set(
                        current['row_operations'])
            finally:
                limited.close()
            if permitted:
                sql(connection, 'REVOKE INSERT ON NESTED_VIEW FROM USER ' +
                    limited_user)
                connection.commit()
        checks.append({'case': 'target-view-only-grants-and-insert-revocation',
                       'passed': True})

    finally:
        client.close()
        (evidence / 'checks.json').write_text(json.dumps(
            {'checks': checks, 'failures': failures}, indent=2)+'\n')
    assert not failures, 'Native view row admission failed'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--runtime', type=Path, required=True)
    parser.add_argument('--evidence', type=Path, required=True)
    options = parser.parse_args()
    result = run_local(options.runtime, options.evidence, qualify)
    raise SystemExit(0 if result['complete'] else 1)
