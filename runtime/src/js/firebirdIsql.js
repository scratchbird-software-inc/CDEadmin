/** Linux desktop ISQL launch (TCP and same-host embedded Engine13). No shell and no server-side process execution. */
import {execFile, spawn} from 'node:child_process';
import {access, copyFile, lstat, mkdir, mkdtemp, readFile, realpath, stat, symlink, writeFile} from 'node:fs/promises';
import {constants} from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const NETWORK_KEYS = ['schema', 'database_target_id', 'dsn', 'user', 'role', 'charset', 'sql_dialect'];
const EMBEDDED_KEYS = [
  'schema', 'attachment_mode', 'database_target_id', 'database', 'filesystem_root',
  'same_host_authority', 'native_provider', 'password_required', 'user', 'role',
  'charset', 'sql_dialect',
];
const STRIPPED_ISC_ENV = ['ISC_PASSWORD', 'ISC_USER', 'ISC_DATABASE', 'ISC_ROLE'];

function text(value, name, maximum=4096, empty=false) {
  if (typeof value !== 'string' || (!empty && !value) || value.length > maximum || /[\0\r\n]/.test(value)) {
    throw new Error(`Invalid ${name}.`);
  }
  return value;
}

function validateEmbeddedAuthority(value) {
  const dbPath = text(value.database, 'local database path');
  const fsRoot = text(value.filesystem_root, 'approved filesystem root');
  if (!path.posix.isAbsolute(dbPath) || dbPath.startsWith('-') || path.posix.normalize(dbPath) !== dbPath) {
    throw new Error('Embedded ISQL requires a canonical absolute local database filename.');
  }
  if (!path.posix.isAbsolute(fsRoot) || path.posix.normalize(fsRoot) !== fsRoot) {
    throw new Error('Embedded ISQL requires a canonical approved filesystem root.');
  }
  const rel = path.posix.relative(fsRoot, dbPath);
  if (!rel || rel.startsWith('..') || path.posix.isAbsolute(rel)) {
    throw new Error('Embedded ISQL database must reside inside its approved filesystem root.');
  }
  if (value.native_provider !== 'Engine13' || value.password_required !== false) {
    throw new Error('Embedded ISQL requires the local Engine13 contract without network credentials.');
  }
  const auth = value.same_host_authority;
  if (!auth || typeof auth !== 'object' || Array.isArray(auth) ||
      Object.keys(auth).some(k => !['platform', 'boot_id', 'hostname', 'database_identity', 'firebird_lock_directory'].includes(k))) {
    throw new Error('Invalid embedded same-host authority.');
  }
  if (auth.platform !== 'linux') throw new Error('Embedded ISQL is qualified on Linux hosts only.');
  text(auth.boot_id, 'host boot identity', 128);
  text(auth.hostname, 'host name', 255);
  const id = auth.database_identity;
  if (!id || typeof id !== 'object' || Array.isArray(id) ||
      Object.keys(id).some(k => !['device', 'inode'].includes(k)) ||
      !/^\d+$/.test(String(id.device || '')) || !/^\d+$/.test(String(id.inode || ''))) {
    throw new Error('Invalid embedded database inode identity.');
  }
  const lockDir = auth.firebird_lock_directory ?? '';
  text(lockDir, 'Firebird lock directory', 4096, true);
  if (lockDir && (!path.posix.isAbsolute(lockDir) || path.posix.normalize(lockDir) !== lockDir)) {
    throw new Error('Invalid Firebird lock directory.');
  }
  return dbPath;
}

export function connectionArguments(value) {
  if (!value || value.schema !== 'scratchrobin.firebird.isql-context@1') {
    throw new Error('Invalid Firebird connection description.');
  }
  if (![1, 3].includes(value.sql_dialect)) throw new Error('Invalid client SQL dialect.');
  if (value.attachment_mode === 'embedded') {
    if (Object.keys(value).some(key => !EMBEDDED_KEYS.includes(key))) {
      throw new Error('Invalid Firebird embedded connection description.');
    }
    const dbPath = validateEmbeddedAuthority(value);
    const args = [
      '-user', text(value.user, 'username', 255),
      '-charset', text(value.charset, 'character set', 63),
      '-sql_dialect', String(value.sql_dialect),
    ];
    if (value.role) args.push('-role', text(value.role, 'role', 255));
    return [...args, dbPath];
  }
  if (Object.keys(value).some(key => !NETWORK_KEYS.includes(key))) {
    throw new Error('Invalid Firebird connection description.');
  }
  const dsn = text(value.dsn, 'TCP database address');
  // Context is generated by the provider; do not reinterpret local files here.
  if (!/^inet[46]?:\/\/[^/]+\//.test(dsn) || dsn.startsWith('-')) throw new Error('An explicit TCP target is required.');
  const args = ['-user', text(value.user, 'username', 255), '-charset', text(value.charset, 'character set', 63),
    '-sql_dialect', String(value.sql_dialect)];
  if (value.role) args.push('-role', text(value.role, 'role', 255));
  return [...args, dsn];
}

export function credentialEnvironment(environment, password) {
  text(password, 'password', 4096);
  const result = {...environment};
  for (const key of STRIPPED_ISC_ENV) delete result[key];
  return {...result, ISC_PASSWORD: password};
}

export function terminalArguments(terminal, executable, args) {
  const name = path.basename(terminal);
  if (name === 'konsole') return ['--separate', '--nofork', '-e', executable, ...args];
  if (name === 'xterm') return ['-e', executable, ...args];
  throw new Error('Choose a Linux Konsole or xterm executable.');
}

export async function inspectExecutable(filename) {
  if (!path.isAbsolute(text(filename, 'local executable'))) throw new Error('Choose an absolute local executable path.');
  const resolved = await realpath(filename);
  if (!(await stat(resolved)).isFile()) throw new Error('The executable must be a regular file.');
  await access(resolved, constants.X_OK);
  return resolved;
}

export async function verifyIsql(executable, environment=process.env) {
  const clean = {...environment};
  for (const key of STRIPPED_ISC_ENV) delete clean[key];
  const version = await new Promise((resolve, reject) => {
    const child = execFile(executable, ['-z'], {env: clean, timeout: 5000, maxBuffer: 32768}, (error, stdout, stderr) => {
      if (error) reject(new Error('Unable to run the selected ISQL version probe.'));
      else resolve(stdout + stderr);
    });
    child.stdin.on('error', error => {
      if (error.code !== 'EPIPE') reject(new Error('ISQL probe input failed.'));
    });
    child.stdin.end('QUIT;\n');
  });
  if (!/ISQL Version: [^\r\n]*V5\.[^\r\n]*Firebird 5\./i.test(version)) throw new Error('Choose a Firebird 5 ISQL executable.');
}

export async function prepareEmbeddedEnvironment(connection, binary, environment=process.env, hostProbe={}) {
  validateEmbeddedAuthority(connection);
  const localBootId = (hostProbe.bootId ?? await readFile('/proc/sys/kernel/random/boot_id', 'utf8')).trim();
  if (!localBootId || localBootId !== connection.same_host_authority.boot_id) {
    throw new Error('Embedded ISQL requires the desktop client to run on the same host as the ScratchRobin server.');
  }
  const rootReal = await realpath(connection.filesystem_root).catch(() => '');
  if (rootReal !== connection.filesystem_root) {
    throw new Error('Approved embedded filesystem root is unavailable on this host.');
  }
  const dbStat = await lstat(connection.database).catch(() => null);
  if (!dbStat || !dbStat.isFile()) {
    throw new Error('Approved local database file is unavailable on this host.');
  }
  const dbReal = await realpath(connection.database).catch(() => '');
  if (dbReal !== connection.database ||
      String(dbStat.dev) !== connection.same_host_authority.database_identity.device ||
      String(dbStat.ino) !== connection.same_host_authority.database_identity.inode) {
    throw new Error('The local database file changed since the server issued this embedded ISQL context.');
  }
  const runtimeRoot = path.dirname(path.dirname(binary));
  const enginePlugin = path.join(runtimeRoot, 'plugins', 'libEngine13.so');
  const libDir = path.join(runtimeRoot, 'lib');
  const engineStat = await stat(enginePlugin).catch(() => null);
  const libStat = await stat(libDir).catch(() => null);
  if (!engineStat?.isFile() || !libStat?.isDirectory()) {
    throw new Error('The selected Firebird 5 runtime does not include the local Engine13 provider.');
  }
  const stageBase = hostProbe.stageParent || os.tmpdir();
  const staged = await mkdtemp(path.join(stageBase, 'scratchrobin-fb-isql-'));
  for (const dirName of ['lib', 'plugins', 'intl', 'tzdata', 'bin']) {
    const candidate = path.join(runtimeRoot, dirName);
    if (await stat(candidate).then(() => true).catch(() => false)) {
      await symlink(candidate, path.join(staged, dirName));
    }
  }
  for (const fileName of ['firebird.msg', 'plugins.conf', 'security5.fdb']) {
    const candidate = path.join(runtimeRoot, fileName);
    if (await stat(candidate).then(s => s.isFile()).catch(() => false)) {
      await copyFile(candidate, path.join(staged, fileName));
    }
  }
  let lockDir = connection.same_host_authority.firebird_lock_directory || '';
  if (lockDir) {
    const lockOk = await stat(lockDir).then(s => s.isDirectory()).catch(() => false);
    if (!lockOk) lockDir = '';
  }
  if (!lockDir) {
    lockDir = path.join(staged, 'lock');
    await mkdir(lockDir, {mode: 0o700});
  }
  await writeFile(path.join(staged, 'databases.conf'), '');
  const secLine = await stat(path.join(staged, 'security5.fdb')).then(() => `SecurityDatabase = ${path.join(staged, 'security5.fdb')}\n`).catch(() => '');
  await writeFile(path.join(staged, 'firebird.conf'), `Providers = Engine13\n${secLine}`);

  const clean = {...environment};
  for (const key of STRIPPED_ISC_ENV) delete clean[key];
  clean.FIREBIRD = staged;
  clean.FIREBIRD_LOCK = lockDir;
  clean.LD_LIBRARY_PATH = clean.LD_LIBRARY_PATH ? `${libDir}:${clean.LD_LIBRARY_PATH}` : libDir;
  return {env: clean, stagedConfigDir: staged, lockDirectory: lockDir};
}

export async function launchIsql({executable, terminal, connection, password, hostProbe}, environment=process.env) {
  if (process.platform !== 'linux') throw new Error('This launcher is qualified for the Linux desktop host.');
  const args = connectionArguments(connection);
  const binary = await inspectExecutable(executable);
  const terminalBinary = await inspectExecutable(terminal);
  const terminalArgs = terminalArguments(terminalBinary, binary, args);
  const isEmbedded = connection.attachment_mode === 'embedded';
  let childEnv;
  let stagedConfigDir = null;
  if (isEmbedded) {
    if (password !== undefined && password !== '') {
      throw new Error('Embedded ISQL does not accept a network password.');
    }
    const prepared = await prepareEmbeddedEnvironment(connection, binary, environment, hostProbe);
    await verifyIsql(binary, prepared.env);
    childEnv = prepared.env;
    stagedConfigDir = prepared.stagedConfigDir;
  } else {
    await verifyIsql(binary, environment);
    childEnv = credentialEnvironment(environment, password);
  }
  const child = spawn(terminalBinary, terminalArgs, {
    env: childEnv, detached: true, stdio: 'ignore', shell: false,
  });
  return new Promise((resolve, reject) => {
    child.once('error', () => reject(new Error('The local terminal could not be started.')));
    child.once('spawn', () => {
      child.unref();
      if (isEmbedded) {
        resolve({
          state: 'process_started',
          pid: child.pid,
          execution_host: 'same-host-local-desktop',
          attachment_mode: 'embedded',
          native_provider: 'Engine13',
          staged_runtime_config: stagedConfigDir,
          native_connection_confirmed: false,
          transaction_outcome: 'owned-by-isql',
        });
      } else {
        resolve({
          state: 'process_started',
          pid: child.pid,
          execution_host: 'local-desktop',
          native_connection_confirmed: false,
          transaction_outcome: 'owned-by-isql',
        });
      }
    });
  });
}

export function setupFirebirdIsql({ipcMain, BrowserWindow, dialog, getOrigin, launch=launchIsql}) {
  const admittedWindow = event => {
    const window = BrowserWindow.fromWebContents(event.sender);
    if (!window || window.isDestroyed() || event.senderFrame !== event.sender.mainFrame ||
        new URL(event.senderFrame.url).origin !== new URL(getOrigin()).origin) {
      throw new Error('ISQL launch requires the local application window.');
    }
    return window;
  };
  ipcMain.handle('firebird-isql:launch', async (event, request) => {
    const window = admittedWindow(event);
    if (process.platform !== 'linux') throw new Error('ISQL launch requires the Linux desktop host.');
    if (!request || Object.keys(request).some(key => !['connection', 'password'].includes(key))) throw new Error('Invalid ISQL launch request.');
    connectionArguments(request.connection);
    if (request.connection?.attachment_mode === 'embedded') {
      if (request.password !== undefined && request.password !== '') {
        throw new Error('Embedded ISQL does not accept a network password.');
      }
    } else {
      text(request.password, 'password', 4096);
    }
    const executable = await dialog.showOpenDialog(window, {
      title: 'Select local Firebird 5 ISQL executable', properties: ['openFile'],
    });
    if (executable.canceled) return {state: 'cancelled_before_launch'};
    admittedWindow(event);
    const terminal = await dialog.showOpenDialog(window, {
      title: 'Select local Konsole or xterm executable', properties: ['openFile'],
    });
    if (terminal.canceled) return {state: 'cancelled_before_launch'};
    admittedWindow(event);
    return launch({...request, executable: executable.filePaths[0], terminal: terminal.filePaths[0]});
  });
}
