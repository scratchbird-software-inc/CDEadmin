/** Linux desktop ISQL launch. No shell and no server-side process execution. */
import {execFile, spawn} from 'node:child_process';
import {access, realpath, stat} from 'node:fs/promises';
import {constants} from 'node:fs';
import path from 'node:path';

function text(value, name, maximum=4096, empty=false) {
  if (typeof value !== 'string' || (!empty && !value) || value.length > maximum || /[\0\r\n]/.test(value)) {
    throw new Error(`Invalid ${name}.`);
  }
  return value;
}
export function connectionArguments(value) {
  if (!value || value.schema !== 'scratchrobin.firebird.isql-context@1' ||
      Object.keys(value).some(key => !['schema', 'database_target_id', 'dsn', 'user', 'role', 'charset', 'sql_dialect'].includes(key))) {
    throw new Error('Invalid Firebird connection description.');
  }
  const dsn = text(value.dsn, 'TCP database address');
  // Context is generated by the provider; do not reinterpret local files here.
  if (!/^inet[46]?:\/\/[^/]+\//.test(dsn) || dsn.startsWith('-')) throw new Error('An explicit TCP target is required.');
  if (![1, 3].includes(value.sql_dialect)) throw new Error('Invalid client SQL dialect.');
  const args = ['-user', text(value.user, 'username', 255), '-charset', text(value.charset, 'character set', 63),
    '-sql_dialect', String(value.sql_dialect)];
  if (value.role) args.push('-role', text(value.role, 'role', 255));
  return [...args, dsn];
}
export function credentialEnvironment(environment, password) {
  text(password, 'password', 4096);
  const result = {...environment};
  for (const key of ['ISC_PASSWORD', 'ISC_USER', 'ISC_DATABASE', 'ISC_ROLE']) delete result[key];
  return {...result, ISC_PASSWORD: password};
}
export function terminalArguments(terminal, executable, args) {
  const name = path.basename(terminal);
  if (name === 'konsole') return ['--separate', '--nofork', '-e', executable, ...args];
  if (name === 'xterm') return ['-e', executable, ...args];
  throw new Error('Choose a Linux Konsole or xterm executable.');
}
export async function inspectExecutable(filename) {
  if (!path.isAbsolute(text(filename, 'local executable'))) throw new Error('Choose an absolute local executable path.');
  const resolved = await realpath(filename);
  if (!(await stat(resolved)).isFile()) throw new Error('The executable must be a regular file.');
  await access(resolved, constants.X_OK);
  return resolved;
}
export async function verifyIsql(executable, environment=process.env) {
  const clean = {...environment};
  for (const key of ['ISC_PASSWORD', 'ISC_USER', 'ISC_DATABASE', 'ISC_ROLE']) delete clean[key];
  const version = await new Promise((resolve, reject) => {
    const child = execFile(executable, ['-z'], {env: clean, timeout: 5000, maxBuffer: 32768}, (error, stdout, stderr) => {
      if (error) reject(new Error('Unable to run the selected ISQL version probe.'));
      else resolve(stdout + stderr);
    });
    child.stdin.on('error', error => {
      if (error.code !== 'EPIPE') reject(new Error('ISQL probe input failed.'));
    });
    child.stdin.end('QUIT;\n');
  });
  if (!/ISQL Version: [^\r\n]*V5\.[^\r\n]*Firebird 5\./i.test(version)) throw new Error('Choose a Firebird 5 ISQL executable.');
}
export async function launchIsql({executable, terminal, connection, password}, environment=process.env) {
  if (process.platform !== 'linux') throw new Error('This launcher is qualified for the Linux desktop host.');
  const args = connectionArguments(connection);
  const binary = await inspectExecutable(executable);
  const terminalBinary = await inspectExecutable(terminal);
  const terminalArgs = terminalArguments(terminalBinary, binary, args);
  await verifyIsql(binary, environment);
  const child = spawn(terminalBinary, terminalArgs, {
    env: credentialEnvironment(environment, password), detached: true, stdio: 'ignore', shell: false,
  });
  return new Promise((resolve, reject) => {
    child.once('error', () => reject(new Error('The local terminal could not be started.')));
    child.once('spawn', () => {
      child.unref();
      resolve({state: 'process_started', pid: child.pid, execution_host: 'local-desktop',
        native_connection_confirmed: false, transaction_outcome: 'owned-by-isql'});
    });
  });
}


export function setupFirebirdIsql({ipcMain, BrowserWindow, dialog, getOrigin, launch=launchIsql}) {
  const admittedWindow = event => {
    const window = BrowserWindow.fromWebContents(event.sender);
    if (!window || window.isDestroyed() || event.senderFrame !== event.sender.mainFrame ||
        new URL(event.senderFrame.url).origin !== new URL(getOrigin()).origin) {
      throw new Error('ISQL launch requires the local application window.');
    }
    return window;
  };
  ipcMain.handle('firebird-isql:launch', async (event, request) => {
    const window = admittedWindow(event);
    if (process.platform !== 'linux') throw new Error('ISQL launch requires the Linux desktop host.');
    if (!request || Object.keys(request).some(key => !['connection', 'password'].includes(key))) throw new Error('Invalid ISQL launch request.');
    connectionArguments(request.connection);
    text(request.password, 'password', 4096);
    const executable = await dialog.showOpenDialog(window, {
      title: 'Select local Firebird 5 ISQL executable', properties: ['openFile'],
    });
    if (executable.canceled) return {state: 'cancelled_before_launch'};
    admittedWindow(event);
    const terminal = await dialog.showOpenDialog(window, {
      title: 'Select local Konsole or xterm executable', properties: ['openFile'],
    });
    if (terminal.canceled) return {state: 'cancelled_before_launch'};
    admittedWindow(event);
    return launch({...request, executable: executable.filePaths[0], terminal: terminal.filePaths[0]});
  });
}
